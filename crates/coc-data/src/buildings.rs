use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum BuildingCategory {
    TownHall,
    Defense,
    Resource,
    Army,
    Other,
    Wall,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum TargetDomain {
    None,
    Ground,
    Air,
    GroundAndAir,
}

impl TargetDomain {
    pub fn can_hit(self, is_air: bool) -> bool {
        match self {
            TargetDomain::None => false,
            TargetDomain::Ground => !is_air,
            TargetDomain::Air => is_air,
            TargetDomain::GroundAndAir => true,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum DefenseMode {
    Default,
    // X-Bow
    XBowGround,
    XBowAirAndGround,
    // Inferno Tower
    InfernoSingle,
    InfernoMulti,
    // Multi-Gear Tower
    MultiGearLongRange,
    MultiGearFastAttack,
    // Spell Tower
    SpellTowerRage,
    SpellTowerPoison,
    SpellTowerInvisibility,
    SpellTowerEarthquake,
    // Town Hall 18 Guardians (guardians.csv: Logger, Longshot, Smasher)
    GuardianLogger,
    GuardianLongshot,
    GuardianSmasher,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum DefenseSpecial {
    None,
    /// Multi-Archer Tower: hits up to `targets` units; focuses if fewer
    MultiTarget { targets: usize },
    /// Ricochet Cannon: bounces to 1 secondary target within `bounce_range` for `bounce_mult` damage
    Ricochet { bounce_range: f32, bounce_mult: f32 },
    /// Super Wizard Tower: chains up to `max_chains` targets within `chain_range` for `chain_mult` damage
    ChainLightning { max_chains: usize, chain_range: f32, chain_mult: f32 },
    /// Air Sweeper: directional cone pushback (buildings.csv: TargetingConeAngle 105, AimRotateStep 45, ShockwavePushStrength 400)
    AirSweeper {
        push_tiles: f32,
        arc_deg: f32,
        rotate_step_deg: f32,
    },
    /// Hidden Tesla: stays hidden until enemy within `trigger_range` or >= 51% destruction
    HiddenTesla { trigger_range: f32 },
    /// Bomb Tower: explodes on death for `death_damage` in `death_radius`
    DeathBomb { death_damage: f32, death_radius: f32 },
    /// Inferno Single: 3-stage ramp-up DPS (stage1 -> stage2 after 1.5s -> stage3 after 5.25s)
    InfernoRamp { dps_stage1: f32, dps_stage2: f32, dps_stage3: f32 },
    /// Scattershot: 90-deg cone splash behind primary target
    ConeSplash { cone_range: f32, cone_damage: f32 },
    /// Weaponized Builder's Hut: spawns repair builder healing damaged buildings within 7 tiles
    BuilderRepair { repair_hps: f32, repair_range: f32 },
    /// Spell Tower: casts spell when enemy enters trigger range
    SpellCaster { cooldown_sec: f32 },
    /// Monolith: deals flat damage + percentage of target's max HP per hit
    PercentMaxHp { bonus_pct: f32 },
    /// Firespitter: directional 150-deg cone rapid burst with 2-target penetrating fireballs
    /// (buildings.csv: TargetingConeAngle 150, AimRotateStep 90, PenetratingRadius 50, PenetratingExtraRange 100)
    DirectionalPierce {
        arc_deg: f32,
        rotate_step_deg: f32,
        pierce_count: usize,
        pierce_radius: f32,
        extra_range: f32,
    },
    /// Revenge Tower: activates at 5 / 25 / 50 buildings destroyed
    RevengeStages,
    /// Hot Candle (Season 4 Crafted Defense): fires 6 -> 4 -> 3 multi-target flames as it melts
    HotCandle {
        stage1_flames: usize,
        stage2_flames: usize,
        stage3_flames: usize,
        first_decay_sec: f32,
        second_decay_sec: f32,
    },
    /// Town Hall 18: spawns its Logger Guardian
    TownHallGuardian,
}

