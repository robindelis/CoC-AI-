#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct HeroEquipmentSpec {
    pub id: EquipmentId,
    pub name: &'static str,
    pub hero: HeroId,
    pub rarity: EquipmentRarity,
    pub max_level: u8,
    pub is_passive: bool,
    pub hp_bonus: f32,
    pub dps_bonus: f32,
    pub heal_on_activation: f32,
    pub ability_description: &'static str,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct HeroSpec {
    pub id: HeroId,
    pub name: &'static str,
    pub max_level: u8,
    /// Base HP at TH18 max level (before dynamic equipment passive bonuses)
    pub base_hp: f32,
    /// Base DPS at TH18 max level (before dynamic equipment passive bonuses)
    pub base_dps: f32,
    /// Total HP including default max-level signature equipment passive boosts
    pub max_hp: f32,
    /// Total DPS including default max-level signature equipment passive boosts
    pub dps: f32,
    pub damage_per_hit: f32,
    pub attack_speed_sec: f32,
    pub move_speed: f32,
    pub range: f32,
    pub movement: MovementMode,
    pub target_domain: TargetDomain,
    pub preferred_target: PreferredTarget,
    pub ability_name: &'static str,
    pub ability_heal: f32,
    pub ability_duration_sec: f32,
    pub default_pet: PetId,
    pub default_equipment: [EquipmentId; 2],
}

